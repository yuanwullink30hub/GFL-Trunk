// Helper function to get combination result
export const getCombinationResult = (shapes) => {
  if (!shapes || shapes.length === 0) return null;
  
  // Sort shapes for consistent key
  const sortedShapes = [...shapes].sort();
  const key = sortedShapes.join('+');
  
  // Try exact match first
  if (combinationResults[key]) {
    return combinationResults[key];
  }
  
  // Try reverse order for two-shape combinations
  if (shapes.length === 2) {
    const reverseKey = shapes.reverse().join('+');
    if (combinationResults[reverseKey]) {
      return combinationResults[reverseKey];
    }
  }
  
  // Fallback: generate a generic combination
  return {
    title: 'Nieuwe Combinatie',
    dutchTitle: `${shapes.length} Dimensies Verbonden`,
    description: `Een unieke combinatie van ${shapes.join(', ')} die nieuwe mogelijkheden opent. Experimenteer verder om de diepere betekenis te ontdekken.`,
    animation: 'pulse-scale',
    color: '#39ff14',
    sources: []
  };
};

