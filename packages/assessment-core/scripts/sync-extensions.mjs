/**
 * Generate src/data/archetypeExtensions.js — the 132 gift and curse texts — from the canon corpus.
 *
 * The corpus itself is ~700 kB per language and belongs on the server; the report PDF needs only the
 * gift and curse of the one extension it renders. This mirrors archetypeQuotes.js, which already holds
 * the 132 Levensles the same way, so all three fields of an extension cell come from one source: the
 * ratified table. Regenerate after a corpus edit:
 *
 *   node scripts/sync-extensions.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const CANON = resolve(HERE, '..', 'src', 'data', 'canon');
const TARGET = resolve(HERE, '..', 'src', 'data', 'archetypeExtensions.js');

const read = (file) => JSON.parse(readFileSync(resolve(CANON, file), 'utf8'));
const cells = (corpus) => {
  const out = {};
  for (const main of Object.keys(corpus.archetypes || {})) {
    for (const e of corpus.archetypes[main].extensions || []) {
      if (!e || !e.main || !e.support) continue;
      out[`${String(e.main).toUpperCase()}_${String(e.support).toUpperCase()}`] = {
        gift: String(e.gift || '').trim(),
        curse: String(e.curse || '').trim(),
      };
    }
  }
  return out;
};

const nl = cells(read('deltawerken_corpus_nl.json'));
const en = cells(read('deltawerken_corpus.json'));
if (Object.keys(nl).length !== 132) throw new Error(`expected 132 Dutch extension cells, got ${Object.keys(nl).length}`);

const table = (obj) => Object.keys(obj).sort().map((k) => `  ${k}: ${JSON.stringify(obj[k])},`).join('\n');

writeFileSync(TARGET, `/**
 * Extension gift & curse — the 132 extended archetypes (Main × Support).
 *
 * GENERATED by scripts/sync-extensions.mjs from canon/deltawerken_corpus*.json — do not edit by hand;
 * edit the corpus and regenerate. Keyed MAIN_SUPPORT (both canonical-12 keys, uppercase), the same keys
 * as EXTENDED_ARCHETYPES and ARCHETYPE_QUOTES. The report renders gift, curse and levensles of one cell;
 * this file carries the first two so the client never ships the whole corpus (~700 kB per language).
 *
 * A key missing from the English table falls back to the Dutch text, as the Levensles table does.
 */

const EXTENSION_CELLS_NL = {
${table(nl)}
};

const EXTENSION_CELLS_EN = {
${table(en)}
};

const cell = (key, lang) => {
  const k = String(key || '').toUpperCase();
  const table = String(lang).toLowerCase().startsWith('en') ? EXTENSION_CELLS_EN : EXTENSION_CELLS_NL;
  return table[k] || EXTENSION_CELLS_NL[k] || null;
};

/** The ratified gift of MAIN_SUPPORT, or '' when the key is unknown. */
export function getExtensionGift(mainKey, supportKey, lang = 'nl') {
  return (cell(\`\${mainKey}_\${supportKey}\`, lang) || {}).gift || '';
}

/** The ratified curse (vloek / trigger) of MAIN_SUPPORT, or '' when the key is unknown. */
export function getExtensionCurse(mainKey, supportKey, lang = 'nl') {
  return (cell(\`\${mainKey}_\${supportKey}\`, lang) || {}).curse || '';
}

export { EXTENSION_CELLS_NL, EXTENSION_CELLS_EN };
`, 'utf8');

console.log(`✓ Extension gift/curse → src/data/archetypeExtensions.js (${Object.keys(nl).length} nl, ${Object.keys(en).length} en)`);
